import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'http://127.0.0.1:4175';
const filename = path.resolve(root, process.argv[2] || 'data/imports/magnum-opus-zaloha-2026-10-19.json');
if (!filename.startsWith(path.join(root, 'data', 'imports') + path.sep)) throw Error('Import must stay inside data/imports');
const backup = JSON.parse(fs.readFileSync(filename, 'utf8'));
const state = backup.app === 'magnum-opus' ? backup.state : backup;
if (!state?.profile || !Array.isArray(state.books) || !Array.isArray(state.ledger)) throw Error('Invalid game backup');
const headers = { Origin: origin, 'X-MO-Request': '1', 'Content-Type': 'application/json' };
const opened = await fetch(origin + '/api/auth/local', { method: 'POST', headers, body: '{}' });
const session = await opened.json();
if (!opened.ok || !session.localMode || !session.account) throw Error('Local personal profile could not be opened');
const cookie = opened.headers.get('set-cookie')?.split(';')[0];
if (!cookie) throw Error('Missing local session');
if (session.save.state.books.length || session.save.state.ledger.length) throw Error('This import only fills a new empty local profile. Existing progress was not changed.');
const result = await fetch(origin + '/api/save', { method: 'PUT', headers: { ...headers, Cookie: cookie, 'X-MO-CSRF': session.csrf }, body: JSON.stringify({ state, expectedRevision: session.save.revision }) });
if (!result.ok) throw Error('Local save import failed: ' + result.status);
fs.writeFileSync(path.join(root, 'data/imports/migration-status.json'), JSON.stringify({ importedAt: new Date().toISOString(), sourceExportedAt: backup.exportedAt || null, file: path.basename(filename), books: state.books.length, includes: ['game-save'], separateStoresTransferred: false }, null, 2));
console.log(JSON.stringify({ imported: true, books: state.books.length, profile: state.profile.name, coins: state.ledger.reduce((n, x) => n + (x.coins || 0), 0), powder: state.ledger.reduce((n, x) => n + (x.powder || 0), 0) }));
