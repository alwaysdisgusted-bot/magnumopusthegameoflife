import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const destination = new URL('../public/vendor/knowledge/', import.meta.url);
const pdf = new URL('../node_modules/pdfjs-dist/', import.meta.url);
const zip = new URL('../node_modules/fflate/', import.meta.url);
const pdfVersion = JSON.parse(readFileSync(new URL('package.json', pdf), 'utf8')).version;
const zipVersion = JSON.parse(readFileSync(new URL('package.json', zip), 'utf8')).version;

mkdirSync(destination, { recursive: true });
function copy(from, to, optional = false) {
  if (optional && !existsSync(from)) return;
  cpSync(from, to, { recursive: true, force: true });
}
copy(new URL('build/pdf.mjs', pdf), new URL('pdf.mjs', destination));
copy(new URL('build/pdf.worker.mjs', pdf), new URL('pdf.worker.mjs', destination));
for (const directory of ['cmaps', 'standard_fonts', 'wasm']) copy(new URL(directory, pdf), new URL(directory, destination));
copy(new URL('iccs', pdf), new URL('iccs', destination), true);
copy(new URL('LICENSE', pdf), new URL('LICENSE-pdfjs.txt', destination));
copy(new URL('umd/index.js', zip), new URL('fflate.js', destination));
copy(new URL('LICENSE', zip), new URL('LICENSE-fflate.txt', destination));
writeFileSync(new URL('versions.json', destination), JSON.stringify({ pdfjs: pdfVersion, fflate: zipVersion }, null, 2) + '\n');
writeFileSync(new URL('README.md', destination), `# Local document extraction\n\nGenerated by scripts/sync-knowledge-vendors.mjs from installed packages.\n\n- pdfjs-dist ${pdfVersion}: Mozilla PDF.js, Apache-2.0. Source: https://github.com/mozilla/pdf.js\n- fflate ${zipVersion}: MIT. Source: https://github.com/101arrowz/fflate\n\nRetain bundled licenses and font/CMap/WASM notices. The browser loads the PDF module and worker with the same package version. Documents and images are read locally; no document is sent to an external recognition service. OCR uses the separate local vendor/ocr assets.\n`);
console.log(`Local knowledge readers ready: PDF.js ${pdfVersion}, fflate ${zipVersion} (${fileURLToPath(destination)}).`);
